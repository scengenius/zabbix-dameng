#!/usr/bin/env python3
"""Render the runtime object grants from the verified DM8 bootstrap SQL."""

import argparse
from pathlib import Path
import re


def identifier(name):
    if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{0,127}", name, flags=re.ASCII) is None:
        raise argparse.ArgumentTypeError(f"Invalid unquoted DM identifier: {name}")
    return name.upper()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("generated", type=Path, help="Directory generated by bootstrap/generate.py")
    parser.add_argument("owner", type=identifier)
    parser.add_argument("runtime", nargs="+", type=identifier)
    args = parser.parse_args()
    if args.owner in args.runtime or len(args.runtime) != len(set(args.runtime)):
        parser.error("Runtime logins must be distinct from each other and from the owner")

    tables = {
        identifier(name)
        for name in re.findall(
            r"^\s*CREATE TABLE\s+([A-Za-z][A-Za-z0-9_]*)\s*\(",
            (args.generated / "ddl.sql").read_text(), re.M | re.I
        )
    }
    parents = {
        identifier(name)
        for name in re.findall(
            r"\bREFERENCES\s+([A-Za-z][A-Za-z0-9_]*)\s*\(",
            (args.generated / "fks.sql").read_text(), re.I
        )
    }
    if (len(tables), len(parents)) != (230, 58) or not parents <= tables:
        parser.error(f"Unexpected 8.0.0 schema: {len(tables)} tables, {len(parents)} FK parents")

    recipients = ", ".join(args.runtime)
    print("whenever sqlerror exit 1 rollback")
    print("set echo off")
    for table in sorted(tables):
        print(f"GRANT SELECT, INSERT, UPDATE, DELETE ON {args.owner}.{table} TO {recipients};")
    for table in sorted(parents):
        print(f"GRANT REFERENCES ON {args.owner}.{table} TO {recipients};")
    print("exit;")


if __name__ == "__main__":
    main()
